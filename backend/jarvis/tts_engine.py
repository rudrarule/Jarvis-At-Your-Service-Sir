"""
Edge-TTS voice engine for J.A.R.V.I.S.

The engine streams MP3 frames from Microsoft Edge-TTS directly into ffplay
when available. It can also synthesize bytes for HTTP clients such as the
existing frontend /tts endpoint.
"""
from __future__ import annotations

import asyncio
import shutil
import time
from collections import OrderedDict
from dataclasses import dataclass
from typing import AsyncIterator, Protocol

try:
    import edge_tts
except ImportError:  # pragma: no cover - exercised only when dependency missing
    edge_tts = None

try:
    import psutil
except ImportError:  # pragma: no cover
    psutil = None


